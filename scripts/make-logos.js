/**
 * Generates src/renderer/js/logos.js from the Simple Icons package
 * (CC0, https://simpleicons.org) so the app ships the logos it needs
 * without loading anything from the internet. Run with `npm run logos`.
 *
 * Outlook, Slack, Xbox and FreeAgent aren't in Simple Icons (removed at the
 * brands' request), so those cards keep their letter tiles. Our own marks
 * (OWN) are added as they are, with their own viewBox.
 */
const fs = require('fs');
const path = require('path');

const pkg = path.join(__dirname, '..', 'node_modules', 'simple-icons');
const data = JSON.parse(fs.readFileSync(path.join(pkg, 'data', 'simple-icons.json'), 'utf8'));
const icons = Array.isArray(data) ? data : data.icons;

// Card provider → Simple Icons slug.
const WANTED = {
	gmail: 'gmail',
	proton: 'protonmail',
	ics: 'googlecalendar',
	clickup: 'clickup',
	github: 'github',
	spotify: 'spotify',
	plex: 'plex',
	claude: 'claude',
	strava: 'strava',
};

// Drift "D" monogram (Drift_Complete_Brand_Pack/Logos/drift-record), on a 100×100 grid.
const OWN = {
	driftrecord: {
		title: 'Drift: Record',
		hex: '#8B5CF6',
		viewBox: '0 0 100 100',
		path: 'M17 12H54C77 12 91 29 91 50C91 72 76 88 54 88H45L55 76H54C70 76 79 64 79 50C79 35 69 24 54 24H29V44H17Z M17 55H29L17 67Z M41 55H54L25 88H12Z M55 76H70L59 88H43Z',
	},
};

const out = {};
for (const [provider, slug] of Object.entries(WANTED)) {
	const svg = fs.readFileSync(path.join(pkg, 'icons', `${slug}.svg`), 'utf8');
	const d = (svg.match(/<path d="([^"]+)"/) || [])[1];
	const meta = icons.find((i) => (i.slug || '') === slug) || {};
	if (!d) {
		throw new Error(`No path found for ${slug}`);
	}
	out[provider] = { title: meta.title || slug, hex: `#${meta.hex || '000000'}`, path: d };
}

Object.assign(out, OWN);

const file = `/**
 * Brand logos (24×24 SVG paths unless a viewBox is given) from Simple Icons ${JSON.parse(fs.readFileSync(path.join(pkg, 'package.json'), 'utf8')).version}, CC0.
 * Generated by scripts/make-logos.js — don't edit by hand.
 */
(function () {
	'use strict';
	window.BD = window.BD || {};
	window.BD.logos = ${JSON.stringify(out, null, '\t').replace(/\n/g, '\n\t')};
}());
`;
fs.writeFileSync(path.join(__dirname, '..', 'src', 'renderer', 'js', 'logos.js'), file);
console.log(`Wrote ${Object.keys(out).length} logos to src/renderer/js/logos.js`);
